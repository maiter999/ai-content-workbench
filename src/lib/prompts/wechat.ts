export type WechatStyle = keyof typeof wechatPrompts

// 构建完整的提示词
export function buildPrompt(
  style: WechatStyle,
  params: {
    topic: string
    industry?: string
    requirements?: string
    materials?: string
  }
): { systemPrompt: string; userPrompt: string } {
  const promptConfig = wechatPrompts[style]

  let systemPrompt = promptConfig.systemPrompt
    .replace('{{行业}}', params.industry || '通用')

  let userPrompt = promptConfig.userPromptTemplate
    .replace('{{topic}}', params.topic || '')

  // 添加行业信息
  if (params.industry) {
    userPrompt = userPrompt.replace('{{industry}}', params.industry)
  } else {
    userPrompt = userPrompt.replace('{{industry}}', '通用')
  }

  // 添加补充要求
  if (params.requirements) {
    userPrompt = userPrompt.replace('{{requirements}}', params.requirements)
  } else {
    userPrompt = userPrompt.replace('{{requirements}}', '无特殊要求')
  }

  // 添加参考素材
  if (params.materials) {
    userPrompt = userPrompt.replace('{{materials}}', params.materials)
  } else {
    userPrompt = userPrompt.replace('{{materials}}', '无')
  }

  return {
    systemPrompt,
    userPrompt,
  }
}
