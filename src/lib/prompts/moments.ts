export type MomentsStyle = keyof typeof momentsPrompts

export function buildMomentsPrompt(
  style: MomentsStyle,
  params: {
    topic: string
    industry?: string
    requirements?: string
    materials?: string
  }
): { systemPrompt: string; userPrompt: string } {
  const promptConfig = momentsPrompts[style]

  let userPrompt = promptConfig.userPromptTemplate
    .replace(/\{\{topic\}\}/g, params.topic || '')
    .replace(/\{\{industry\}\}/g, params.industry || '通用')
    .replace(/\{\{requirements\}\}/g, params.requirements || '无特殊要求')
    .replace(/\{\{materials\}\}/g, params.materials || '无')

  return {
    systemPrompt: promptConfig.systemPrompt,
    userPrompt,
  }
}
